"""Render genuine artist-authored ATOM actions into transparent PNGs.

Run from ironframe/:
blender -b art/blender/atom_master.blend --python tools/blender/export_frames.py -- --config config/pipeline.json
No meshes, rigs, poses, cameras or fake sprites are generated by this script.
"""
import bpy
import json
import sys
from pathlib import Path
from bpy_extras.object_utils import world_to_camera_view


def fail(message):
    raise RuntimeError("IRONFRAME SOURCE ART ERROR: " + message)


args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
if len(args) != 2 or args[0] != "--config":
    fail("Use -- --config config/pipeline.json")
config_file = Path(args[1]).resolve()
root = config_file.parent.parent
cfg = json.loads(config_file.read_text(encoding="utf8"))
source = cfg["source"]
render = cfg["render"]
raw = root / "build" / "raw"
scene = bpy.context.scene

if cfg["simulationHz"] != 60 or cfg["sourceFps"] not in (30, 60):
    fail("Export requires 60Hz simulation and 30/60fps authored animation")
rig = bpy.data.objects.get(source["rig"])
if rig is None or rig.type != "ARMATURE":
    fail("Missing artist-authored ATOM_RIG armature; no procedural robot will be created")
if not rig.animation_data:
    fail("Rig has no animation data; create the approved actions first")
for key in ("origin", "ground", "forearmSocket"):
    if bpy.data.objects.get(source[key]) is None:
        fail("Missing manually positioned object: " + source[key])
for facing, name in render["cameras"].items():
    cam = bpy.data.objects.get(name)
    if cam is None or cam.type != "CAMERA":
        fail("Missing authored facing camera: " + name)
    if cam.animation_data and (cam.animation_data.action or cam.animation_data.nla_tracks):
        fail("Ordinary sprite camera must not be animated: " + name)
for entry in cfg["actions"]:
    action = bpy.data.actions.get(entry["blenderAction"])
    if action is None:
        fail("Missing authored action: " + entry["blenderAction"])
    if action.frame_range[0] > 1 or action.frame_range[1] < entry["frames"]:
        fail("Action " + entry["blenderAction"] + " must cover its full approved source frame range")
layers = {v.name for v in scene.view_layers}
for render_pass in cfg["passes"]:
    for layer in render_pass["layers"]:
        if layer["viewLayer"] not in layers:
            fail("Missing artist-configured view layer: " + layer["viewLayer"])
if scene.render.engine not in {"BLENDER_EEVEE_NEXT", "BLENDER_EEVEE", "CYCLES"}:
    fail("Choose a validated Blender Eevee or Cycles render engine")

old = (scene.camera, scene.render.filepath, scene.render.resolution_x,
       scene.render.resolution_y, scene.render.resolution_percentage,
       scene.render.film_transparent, scene.frame_current,
       rig.animation_data.action)
scene.render.image_settings.file_format = "PNG"
scene.render.image_settings.color_mode = "RGBA"
scene.render.film_transparent = True
scene.render.resolution_x = render["width"]
scene.render.resolution_y = render["height"]
scene.render.resolution_percentage = 100


def pixel_location(object_name):
    pt = world_to_camera_view(scene, scene.camera,
                              bpy.data.objects[object_name].matrix_world.translation)
    if pt.z <= 0:
        fail("Anchor is behind active camera: " + object_name)
    return {"x": round(pt.x * render["width"], 4),
            "y": round((1 - pt.y) * render["height"], 4)}


index = {"schemaVersion": 1, "characterId": cfg["characterId"],
         "canvas": {"width": render["width"], "height": render["height"]},
         "frames": []}
try:
    for entry in cfg["actions"]:
        try:
            rig.animation_data.action = bpy.data.actions[entry["blenderAction"]]
        except Exception as exc:
            fail("Cannot bind action " + entry["blenderAction"] +
                 "; check Blender action slots: " + str(exc))
        for facing, camera in render["cameras"].items():
            scene.camera = bpy.data.objects[camera]
            for render_pass in cfg["passes"]:
                if entry["id"] not in render_pass["actions"]:
                    continue
                for i in range(entry["frames"]):
                    scene.frame_set(i + 1)
                    bpy.context.view_layer.update()
                    pivot = pixel_location(source["origin"])
                    anchor = pixel_location(source["ground"])
                    socket = pixel_location(source["forearmSocket"])
                    for layer in render_pass["layers"]:
                        folder = raw / cfg["characterId"] / facing / entry["id"] / render_pass["state"] / layer["id"]
                        folder.mkdir(parents=True, exist_ok=True)
                        filename = folder / ("frame_%04d.png" % i)
                        scene.render.filepath = str(filename)
                        bpy.ops.render.render(write_still=True, layer=layer["viewLayer"])
                        if not filename.is_file() or filename.stat().st_size == 0:
                            fail("Blender produced no render: " + str(filename))
                        index["frames"].append({
                            "action": entry["id"], "facing": facing,
                            "state": render_pass["state"], "layer": layer["id"],
                            "index": i, "file": filename.relative_to(raw).as_posix(),
                            "holdTicks": 60 // cfg["sourceFps"],
                            "pivot": pivot, "groundAnchor": anchor,
                            "sockets": {"forearm_r": socket}
                        })
    raw.mkdir(parents=True, exist_ok=True)
    (raw / "frames-index.json").write_text(json.dumps(index, indent=2) + "\n", encoding="utf8")
    print("Rendered %d genuine Blender PNG frames" % len(index["frames"]))
finally:
    camera, filepath, x, y, percentage, transparent, frame, action = old
    scene.camera = camera
    scene.render.filepath = filepath
    scene.render.resolution_x = x
    scene.render.resolution_y = y
    scene.render.resolution_percentage = percentage
    scene.render.film_transparent = transparent
    scene.frame_set(frame)
    rig.animation_data.action = action
